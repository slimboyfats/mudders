/**
 * Content tooling (§2c.5):
 *   pnpm content:validate        schema + reference resolution, tests, scenario stubs, id lock,
 *                                near-duplicate configs, generated docs up to date
 *   pnpm content:new <type> <name>   scaffold manifest, test, scenario stub (+ behaviour for code types)
 *   pnpm content:docs            regenerate docs/WEAPONS.md from manifests
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
  CONTENT_TYPES,
  CONTENT_TYPE_FOLDERS,
  ScenarioSchema,
  contentTypeOf,
  type ContentType,
} from '@mudders/shared';
import { ContentError, canonicalJson, resolveContent, type ResolvedContent } from '@mudders/sim';
import { behaviourPaths, discoverContent } from '../src/glob';

const PKG = resolve(import.meta.dirname, '..');
const ROOT = resolve(PKG, '../..');
const SCENARIOS = resolve(ROOT, 'scenarios');
const WEAPONS_MD = resolve(ROOT, 'docs/WEAPONS.md');
const PACK = 'core';
const PACK_DIR = resolve(PKG, PACK);
const LOCK = resolve(PACK_DIR, 'ids.lock.json');

function readJson<T>(p: string): T {
  return JSON.parse(readFileSync(p, 'utf8')) as T;
}
function writeJson(p: string, v: unknown): void {
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, `${JSON.stringify(v, null, 2)}\n`);
}

// ── docs ────────────────────────────────────────────────────────────────────────────────────

export function weaponsMarkdown(c: ResolvedContent): string {
  const lines = [
    '# Weapons',
    '',
    '<!-- GENERATED by `pnpm content:docs` from content manifests. Do not edit by hand. -->',
    '',
    `Content hash \`${c.hash}\` · packs ${c.packs.map((p) => `${p.name}@${p.version}`).join(', ')}`,
    '',
    '| Id | Name | Category | Flight | Impact | Price | Since |',
    '| -- | ---- | -------- | ------ | ------ | ----- | ----- |',
  ];
  for (const w of c.list('weapon')) {
    const impact = w.impact
      .map((i) =>
        'explosion' in i
          ? `${i.explosion.ref ?? 'explosion'} r${i.explosion.radius} dmg ${i.explosion.damage} (${i.explosion.damageType})`
          : `${i.terrainOp.ref ?? i.terrainOp.behaviour} r${i.radius}`,
      )
      .join('; ');
    lines.push(
      `| \`${w.id}\` | ${w.meta.name} | ${w.meta.category ?? ''} | ${w.flight.ref ?? w.flight.behaviour} | ${impact} | ${w.shop.price} × ${w.shop.pack} | ${w.meta.since} |`,
    );
  }
  lines.push('', '## Descriptions', '');
  for (const w of c.list('weapon'))
    lines.push(`- **${w.meta.name}** (\`${w.id}\`): ${w.meta.description}`);
  return `${lines.join('\n')}\n`;
}

// ── validate ────────────────────────────────────────────────────────────────────────────────

function findInlineDuplicates(c: ResolvedContent): string[] {
  // Inline (non-`use`) objects with ≥3 keys that appear verbatim in two items should be a shared
  // item referenced with `use` + overrides (§2c.1: copy-paste is a review failure).
  const seen: Record<string, string> = {};
  const out: string[] = [];
  const walk = (v: unknown, owner: string, path: string, top: boolean): void => {
    if (Array.isArray(v)) {
      v.forEach((x, i) => walk(x, owner, `${path}.${i}`, false));
      return;
    }
    if (!v || typeof v !== 'object') return;
    const o = v as Record<string, unknown>;
    if (!top && !('use' in o) && Object.keys(o).length >= 3) {
      const key = canonicalJson(o);
      const prev = seen[key];
      if (prev && !prev.startsWith(`${owner}:`)) {
        out.push(`${owner}:${path} duplicates ${prev}; extract it into an item and \`use\` it`);
      } else seen[key] = `${owner}:${path}`;
    }
    for (const k of Object.keys(o))
      if (k !== 'meta') walk(o[k], owner, path ? `${path}.${k}` : k, false);
  };
  for (const id of c.ids) walk(c.raw(id), id, '', true);
  return out;
}

export function validate(): string[] {
  const problems: string[] = [];
  let c: ResolvedContent;
  try {
    c = resolveContent(discoverContent());
  } catch (e) {
    if (e instanceof ContentError) return e.problems;
    throw e;
  }

  const lock = existsSync(LOCK) ? readJson<string[]>(LOCK) : [];
  for (const id of lock)
    if (!c.has(id))
      problems.push(
        `${id}: id is in ids.lock.json but no longer exists (ids are permanent; deprecate instead)`,
      );
  for (const id of c.ids)
    if (!lock.includes(id)) problems.push(`${id}: missing from ${PACK}/ids.lock.json`);

  const behaviourFolders = behaviourPaths().map((p) => p.slice(0, -'/behaviour.ts'.length));
  for (const id of c.ids) {
    const type = contentTypeOf(id)!;
    const dir = resolve(PACK_DIR, CONTENT_TYPE_FOLDERS[type], id.slice(type.length + 1));
    const tests = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.test.ts')) : [];
    if (tests.length === 0) problems.push(`${id}: no *.test.ts in ${dir}`);
    const scen = resolve(SCENARIOS, `${id}.json`);
    if (!existsSync(scen)) {
      problems.push(`${id}: no scenario stub at scenarios/${id}.json`);
      continue;
    }
    const parsed = ScenarioSchema.safeParse(readJson<unknown>(scen));
    if (!parsed.success) {
      problems.push(
        `scenarios/${id}.json: ${parsed.error.issues.map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')}`,
      );
      continue;
    }
    const sc = parsed.data;
    if (!c.has(sc.mode)) problems.push(`scenarios/${id}.json: unknown mode ${sc.mode}`);
    if (sc.subject && !c.has(sc.subject))
      problems.push(`scenarios/${id}.json: unknown subject ${sc.subject}`);
    for (const inp of sc.inputs) {
      if (inp.action.type === 'selectWeapon' && !c.has(inp.action.weapon)) {
        problems.push(`scenarios/${id}.json: unknown weapon ${inp.action.weapon}`);
      }
    }
  }
  for (const b of c.behaviours.list()) {
    const type = contentTypeOf(b.id);
    const folder = type
      ? `${PACK}/${CONTENT_TYPE_FOLDERS[type]}/${b.id.slice(type.length + 1)}`
      : '';
    if (!behaviourFolders.includes(folder))
      problems.push(`behaviour ${b.id} must live in ${folder}/behaviour.ts`);
  }
  problems.push(...findInlineDuplicates(c));

  const md = weaponsMarkdown(c);
  if (!existsSync(WEAPONS_MD) || readFileSync(WEAPONS_MD, 'utf8') !== md) {
    problems.push('docs/WEAPONS.md is out of date; run pnpm content:docs');
  }
  return problems;
}

// ── new ─────────────────────────────────────────────────────────────────────────────────────

const SINCE = () =>
  `${PACK}@${readJson<{ version: string }>(resolve(PACK_DIR, 'pack.json')).version}`;

function template(type: ContentType, id: string, name: string): Record<string, unknown> {
  const meta = { name, description: `TODO: describe ${id}.`, since: SINCE() };
  const base = { id, schemaVersion: 1, meta };
  switch (type) {
    case 'weapon':
      return {
        ...base,
        meta: { ...meta, category: 'explosive' },
        flight: { use: 'flight.ballistic' },
        triggers: ['onSolid', 'onTank'],
        impact: [{ explosion: { use: 'explosion.standard' } }],
        shop: { price: 1000, pack: 5, tier: 0 },
        ai: { expectedDamage: 30, terrainValue: 0.2 },
      };
    case 'explosion':
      return { ...base, extends: 'explosion.standard' };
    case 'material':
      return {
        ...base,
        cell: 0,
        settle: 'fall',
        density: 100,
        strength: {},
        cohesion: 0,
        coating: false,
      };
    case 'mode':
      return { ...base, extends: 'mode.classic' };
    default:
      return { ...base, behaviour: id };
  }
}

const DEFINE: Partial<Record<ContentType, string>> = {
  gen: 'defineGenerator',
  flight: 'defineFlight',
  terrainop: 'defineTerrainOp',
};

function behaviourStub(type: ContentType, id: string): string | null {
  const fn = DEFINE[type];
  if (!fn) return null;
  const body =
    type === 'gen'
      ? `  generate(api, _p, players) {\n    // TODO: fill api.grid; return a spawn column per player.\n    return { spawns: Array.from({ length: players }, (_, i) => Math.floor(((i + 1) * api.grid.width) / (players + 1))) };\n  },`
      : type === 'flight'
        ? `  maxTicks: () => 900,\n  step(api, proj) {\n    // TODO\n    proj.vy += api.gravity;\n    proj.x += proj.vx;\n    proj.y += proj.vy;\n  },`
        : `  start(api, _p, c) {\n    // TODO: change cells around (c.x, c.y), then mark them dirty.\n    api.grid.markDirty(c.x - c.radius, c.y - c.radius, c.x + c.radius, c.y + c.radius);\n    return null;\n  },`;
  return `import { z } from '@mudders/shared';\nimport { ${fn} } from '@mudders/sim';\n\nconst params = z.strictObject({});\n\nexport default ${fn}<z.infer<typeof params>>({\n  kind: '${type}',\n  id: '${id}',\n  version: 1,\n  params,\n${body}\n});\n`;
}

function scaffold(typeArg: string, name: string): string[] {
  const type = (CONTENT_TYPES as readonly string[]).includes(typeArg)
    ? (typeArg as ContentType)
    : CONTENT_TYPES.find((t) => CONTENT_TYPE_FOLDERS[t] === typeArg);
  if (!type || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) {
    throw new Error(`usage: content:new <${CONTENT_TYPES.join('|')}> <kebab-name>`);
  }
  const id = `${type}.${name}`;
  const dir = resolve(PACK_DIR, CONTENT_TYPE_FOLDERS[type], name);
  if (existsSync(dir)) throw new Error(`${id} already exists at ${dir}`);
  const title = name.replace(
    /(^|-)([a-z])/g,
    (_m, sp: string, ch: string) => (sp ? ' ' : '') + ch.toUpperCase(),
  );
  const written: string[] = [];
  const write = (p: string, s: string) => {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, s);
    written.push(p);
  };
  write(resolve(dir, 'manifest.json'), `${JSON.stringify(template(type, id, title), null, 2)}\n`);
  const stub = behaviourStub(type, id);
  if (stub) write(resolve(dir, 'behaviour.ts'), stub);
  write(
    resolve(dir, `${name}.test.ts`),
    `import { describe, expect, it } from 'vitest';\nimport { loadContent } from '../../../src/index';\n\ndescribe('${id}', () => {\n  it('loads and resolves', () => {\n    expect(loadContent().has('${id}')).toBe(true);\n  });\n\n  it.todo('does what its description says');\n});\n`,
  );
  const shot =
    type === 'weapon'
      ? [
          { t: 0, player: 0, action: { type: 'selectWeapon', weapon: id } },
          { t: 0, player: 0, action: { type: 'aim', angle: 55, power: 605 } },
          { t: 0, player: 0, action: { type: 'fire' } },
        ]
      : [];
  const scen = resolve(SCENARIOS, `${id}.json`);
  writeJson(scen, {
    id,
    schemaVersion: 1,
    description: `Stub: show ${id}.`,
    subject: id,
    mode: 'mode.classic',
    seed: 7,
    players: 2,
    map: { width: 800, height: 400 },
    tanks: [{ x: 150 }, { x: 620 }],
    turnOrder: [0, 1],
    wind: 0,
    inputs: shot,
    capture: { maxTicks: 900, untilSettled: true, extraTicks: 45 },
  });
  written.push(scen);
  const packPath = resolve(PACK_DIR, 'pack.json');
  const pack = readJson<{ items: string[] }>(packPath);
  pack.items = [...pack.items, id].sort();
  writeJson(packPath, pack);
  const lock = existsSync(LOCK) ? readJson<string[]>(LOCK) : [];
  writeJson(LOCK, [...lock, id].sort());
  written.push(packPath, LOCK);
  return written;
}

export function main(args: string[]): number {
  const [cmd, ...rest] = args;
  try {
    if (cmd === 'validate') {
      const problems = validate();
      if (problems.length) {
        console.error(
          `content:validate found ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}`,
        );
        return 1;
      }
      const c = resolveContent(discoverContent());
      console.log(`content ok: ${c.ids.length} items, hash ${c.hash}`);
      return 0;
    }
    if (cmd === 'docs') {
      writeFileSync(WEAPONS_MD, weaponsMarkdown(resolveContent(discoverContent())));
      console.log(WEAPONS_MD);
      return 0;
    }
    if (cmd === 'new') {
      const files = scaffold(rest[0] ?? '', rest[1] ?? '');
      for (const f of files) console.log(f);
      return 0;
    }
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    return 1;
  }
  console.error('usage: content <validate|docs|new <type> <name>>');
  return 2;
}
